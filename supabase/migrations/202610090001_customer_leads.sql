create table if not exists public.customer_leads (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique,
  customer_name text not null check (char_length(customer_name) between 2 and 100),
  phone text not null check (phone ~ '^[0-9]{10}$'),
  address text not null check (char_length(address) between 5 and 500),
  locality text not null check (char_length(locality) between 2 and 100),
  pincode text not null references public.serviceable_pincodes(pincode),
  delivery_notes text not null default '' check (char_length(delivery_notes) <= 300),
  maps_url text,
  items jsonb not null check (jsonb_typeof(items) = 'array'),
  subtotal_paise bigint not null check (subtotal_paise >= 0),
  status text not null default 'new_lead' check (status in ('new_lead','contacted','order_confirmed','out_for_delivery','delivered','cancelled')),
  admin_notes text not null default '' check (char_length(admin_notes) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists customer_leads_created_at_idx on public.customer_leads (created_at desc);
create index if not exists customer_leads_status_idx on public.customer_leads (status);
alter table public.serviceable_pincodes enable row level security;
alter table public.customer_leads enable row level security;
drop policy if exists "Active PIN codes are readable by visitors" on public.serviceable_pincodes;
create policy "Active PIN codes are readable by visitors" on public.serviceable_pincodes for select using (is_active = true);
drop policy if exists "Admins manage PIN codes" on public.serviceable_pincodes;
create policy "Admins manage PIN codes" on public.serviceable_pincodes for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Admins read customer enquiries" on public.customer_leads;
create policy "Admins read customer enquiries" on public.customer_leads for select to authenticated using (public.is_admin());
drop policy if exists "Admins update customer enquiries" on public.customer_leads;
create policy "Admins update customer enquiries" on public.customer_leads for update to authenticated using (public.is_admin()) with check (public.is_admin());
grant select on public.serviceable_pincodes to anon, authenticated;
grant select, update on public.customer_leads to authenticated;
